// Token Radar model (token-radar-01): one sealed snapshot in, one ranked board out.
//
// WHAT THE BOARD RANKS
// A protocol is rankable when its DefiLlama record carries no token (mcap_usd, gecko_id and
// symbol all null) and it is not a wrapped, staked or bridged product of a token that already
// trades: its category is not Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking,
// Restaked BTC or CEX, its name carries no whole word wrapped / staked / staking, and it does
// not end in a version marker (V2, v2, 2.0 and the like). That is the watchlist's own rule,
// applied to the whole snapshot instead of only the $50M floor. The board carries every
// rankable protocol (198 on this snapshot: the 40 watchlist slugs plus 158 below the floor),
// so the watchlist is the floor, never the ceiling, and no name is ever hand-picked.
//
// IMPLIED VALUE — radar-2
// The value a launch would be worth if the protocol's record stayed as it is. It is the
// entry's own claim, never a price and never a prediction that a token is issued. Every
// input comes from the snapshot's own figures:
//
//   comp       = the category's own market multiple: the median market-cap / TVL ratio of the
//                live-token protocols in the same category (at least 3 of them), else the
//                median over every live-token protocol; clamped to [0.05, 1.00]. A lending
//                protocol is priced like lending protocols that already trade, a DEX like
//                DEXes — not like everything at one flat rate.
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.70 + min(age_days, 1095) / 1095 x 0.30   (age unknown: 365 days)
//                Age is the time since DefiLlama first listed the protocol: how long it has
//                run with no token on record. Older, still-unlaunched protocols have a
//                longer track record behind the same TVL.
//   breadth    = 1 + min(chains - 1, 4) x 0.02   (at most 1.08: TVL spread over more chains
//                is stickier than TVL on one chain)
//   implied    = max(1, round(tvl_usd x comp x growthMult x maturity x breadth))
//
// Live-token protocols are never ranked: the board shows their market cap as a fact in the
// separate Live tab, and they serve only as the comparables that price the pre-token board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
